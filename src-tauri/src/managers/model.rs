    pub fn register_cloud_models(&self, cloud_models: &[crate::remote_asr::AsrGatewayModel]) {
        if cloud_models.is_empty() {
            warn!("[anonen-cloud] /v1/models returned no models; keeping existing cards");
            return;
        }

        let base_url = self.anonen_cloud_base_url();

        let mut models = self.available_models.lock().unwrap();
        let mut configs = self.remote_model_configs.lock().unwrap();
        let mut order = self.cloud_order.lock().unwrap();
        let mut marks = self.cloud_policy_marks.lock().unwrap();

        models.retain(|id, _| !id.starts_with(ANONEN_CLOUD_MODEL_PREFIX));
        configs.retain(|id, _| !id.starts_with(ANONEN_CLOUD_MODEL_PREFIX));
        marks.clear();

        order.clear();
        order.extend(
            cloud_models
                .iter()
                .map(|cm| format!("{}{}", ANONEN_CLOUD_MODEL_PREFIX, cm.id)),
        );

        for cm in cloud_models.iter() {
            let card_id = format!("{}{}", ANONEN_CLOUD_MODEL_PREFIX, cm.id);

            marks.insert(
                card_id.clone(),
                crate::model_data_policy::fingerprint(
                    &cm.id,
                    &cm.training_use,
                    &cm.retention_kind,
                    cm.retention_days,
                ),
            );

            let label = if cm.provider_label.is_empty() {
                cm.description.clone()
            } else {
                cm.provider_label.clone()
            };
            models.insert(
                card_id.clone(),
                remote_model_info(
                    &card_id,
                    &cm.display_name,
                    &cm.description,
                    &label,
                    cm.accuracy_score,
                    cm.speed_score,
                    cm.is_recommended,
                    cm.price_per_hour,
                    cm.supports_translation,
                    cm.supported_languages.clone(),
                    cm.usage_multiplier,
                ),
            );
            configs.insert(
                card_id,
                RemoteModelConfig {
                    base_url: base_url.clone(),
                    model_id: cm.id.clone(),
                },
            );
        }
        info!(
            "[anonen-cloud] registered {} cloud model card(s) from /v1/models",
            cloud_models.len()
        );
    }

