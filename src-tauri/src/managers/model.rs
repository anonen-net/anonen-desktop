    pub fn get_available_models(&self) -> Vec<ModelInfo> {
        let models = self.available_models.lock().unwrap();
        let order = self.cloud_order.lock().unwrap();
        let rank = |id: &str| match order.iter().position(|known| known == id) {
            Some(i) => (0usize, i, String::new()),
            None => (1usize, 0usize, id.to_string()),
        };
        let mut out: Vec<ModelInfo> = models.values().cloned().collect();
        out.sort_by(|a, b| rank(&a.id).cmp(&rank(&b.id)));
        out
    }

